import Foundation

enum NotesShortcutError: LocalizedError {
    case invalidConfiguration, invalidInput, alreadyRunning, unavailable, interrupted, unverifiedOutput
    var errorDescription: String? {
        switch self {
        case .invalidConfiguration: "请先配置已安装的备忘录快捷指令及其目标文件夹"
        case .invalidInput: "备忘录需要单行标题和完整正文，且参数不能超过限制"
        case .alreadyRunning: "已有备忘录快捷指令在运行"
        case .unavailable: "无法打开备忘录快捷指令，请核对手机上的名称"
        case .interrupted: "备忘录快捷指令未得到有效结果；请核对系统备忘录，不会自动重复创建"
        case .unverifiedOutput: "快捷指令已返回，但回传正文与提交正文不一致；请核对系统备忘录，不会自动重复创建"
        }
    }
}

struct NotesShortcutConfiguration: Codable, Equatable, Sendable {
    var createShortcut: String
    var folderName: String
    func validate() throws {
        guard [createShortcut, folderName].allSatisfy({
            !$0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty && $0.count <= 160 &&
            !$0.contains(where: { $0.isNewline }) && !$0.contains("\0")
        }) else { throw NotesShortcutError.invalidConfiguration }
    }
}

/// A callback belongs to one actual tool attempt. Its URL is generated by the
/// host, never accepted from model output or restored after an app restart.
struct NotesShortcutInvocation: Equatable, Sendable {
    enum Status: String, CaseIterable { case success, cancel, error }
    struct Callback: Equatable {
        let status: Status
        let output: String?
    }
    let id: UUID
    let taskID: UUID
    let digest: String
    let expiresAt: Date
    let configuration: NotesShortcutConfiguration
    let text: String

    init(id: UUID = UUID(), taskID: UUID, digest: String, title: String, body: String,
         configuration: NotesShortcutConfiguration, now: Date = Date()) throws {
        try configuration.validate()
        guard digest.range(of: "^[0-9a-f]{64}$", options: .regularExpression) != nil,
              !title.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, title.count <= 160,
              !title.contains(where: { $0.isNewline }), !title.contains("\0"),
              !body.isEmpty, body.count <= 6000, body.utf8.count <= 24000, !body.contains("\0") else {
            throw NotesShortcutError.invalidInput
        }
        self.id = id; self.taskID = taskID; self.digest = digest
        self.configuration = configuration; text = title + "\n" + body
        expiresAt = now.addingTimeInterval(180)
    }

    func callbackURL(_ status: Status) -> URL {
        var url = URLComponents()
        url.scheme = "phoneagent"; url.host = "notes-result"; url.path = "/" + id.uuidString
        url.queryItems = [URLQueryItem(name: "task", value: taskID.uuidString),
                          URLQueryItem(name: "digest", value: digest), URLQueryItem(name: "status", value: status.rawValue)]
        return url.url!
    }

    var launchURL: URL {
        var url = URLComponents()
        url.scheme = "shortcuts"; url.host = "x-callback-url"; url.path = "/run-shortcut"
        url.queryItems = [URLQueryItem(name: "name", value: configuration.createShortcut),
                          URLQueryItem(name: "input", value: "text"), URLQueryItem(name: "text", value: text)] +
            Status.allCases.map { URLQueryItem(name: "x-" + $0.rawValue, value: callbackURL($0).absoluteString) }
        return url.url!
    }

    func callback(from url: URL, now: Date) -> Callback? {
        guard now <= expiresAt, url.absoluteString.utf8.count <= 100000,
              let parts = URLComponents(url: url, resolvingAgainstBaseURL: false),
              parts.scheme == "phoneagent", parts.host == "notes-result",
              parts.user == nil, parts.password == nil, parts.port == nil, parts.fragment == nil,
              parts.path == "/" + id.uuidString, let items = parts.queryItems,
              items.count <= 5, Set(items.map(\.name)).count == items.count,
              Set(items.map(\.name)).isSubset(of: ["task", "digest", "status", "result", "errorMessage"]) else { return nil }
        let values = Dictionary(uniqueKeysWithValues: items.compactMap { item in item.value.map { (item.name, $0) } })
        guard values.count == items.count, values["task"] == taskID.uuidString, values["digest"] == digest,
              let status = values["status"].flatMap(Status.init(rawValue:)) else { return nil }
        switch status {
        case .success:
            guard values["errorMessage"] == nil, let output = values["result"], output.utf8.count <= 32000 else { return nil }
            return Callback(status: status, output: output)
        case .cancel:
            guard values["result"] == nil, values["errorMessage"] == nil else { return nil }
        case .error:
            guard values["result"] == nil, (values["errorMessage"]?.utf8.count ?? 0) <= 8000 else { return nil }
        }
        return Callback(status: status, output: nil)
    }
}

/// Invalid, duplicate and late callbacks never consume another task's attempt.
struct NotesShortcutSession {
    private(set) var active: NotesShortcutInvocation?
    private var usedIDs = Set<UUID>()
    mutating func begin(_ invocation: NotesShortcutInvocation) throws {
        guard active == nil else { throw NotesShortcutError.alreadyRunning }
        guard !usedIDs.contains(invocation.id) else { throw NotesShortcutError.interrupted }
        usedIDs.insert(invocation.id); active = invocation
    }
    mutating func take(_ url: URL, now: Date) -> NotesShortcutInvocation.Callback? {
        guard let invocation = active, let callback = invocation.callback(from: url, now: now) else { return nil }
        active = nil; return callback
    }
    @discardableResult mutating func cancel(id: UUID) -> Bool {
        guard active?.id == id else { return false }; active = nil; return true
    }
}

/// The cancellation signal is visible immediately, before the main actor can
/// process its queued cleanup or a racing URL-open callback.
final class NotesShortcutCancellation: @unchecked Sendable {
    private let lock = NSLock()
    private var cancelled = false
    var isCancelled: Bool { lock.lock(); defer { lock.unlock() }; return cancelled }
    func cancel() { lock.lock(); cancelled = true; lock.unlock() }
}
