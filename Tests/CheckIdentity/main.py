#!/usr/bin/env python3
"""Real runner boundary replays; all mutations affect private synthetic files."""
from pathlib import Path
import json
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]


class CheckIdentityChecks(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="offline-check-identity-")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name) / "source with spaces"
        self.manifest = Path(self.temporary.name) / "inputs.json"
        for name, contents in {"PhoneAgent/App.swift": "synthetic app",
                               "Shared/Types.swift": "synthetic types",
                               "PhoneAgent.xcodeproj/project.pbxproj": "synthetic project",
                               "Tests/Fixture/input.json": "synthetic input",
                               "Tools/Probe.swift": "synthetic probe"}.items():
            self.write(name, contents)
        for name in ("check.sh", "check-inputs.py", "source-manifest.py"):
            self.write("scripts/" + name, (ROOT / "scripts" / name).read_text())
        self.digest = self.cli("create", check=True).stdout.strip()

    def write(self, name, contents):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)

    def cli(self, operation, check=False):
        command = ["python3", str(self.root / "scripts/check-inputs.py"), operation,
                   str(self.root), str(self.manifest)]
        if operation == "check":
            command += ["--expected-digest", self.digest]
        return subprocess.run(command, capture_output=True, text=True, check=check)

    def test_unchanged_full_input_set(self):
        self.assertEqual(self.cli("check").returncode, 0)

    def test_added_removed_and_modified_consumed_inputs(self):
        for name, action, key in [("Tests/Fixture/new.json", "add", "added"),
                                  ("Tests/Fixture/input.json", "remove", "removed"),
                                  ("Tools/Probe.swift", "modify", "modified"),
                                  ("scripts/check.sh", "modify", "modified"),
                                  ("Shared/Types.swift", "modify", "modified")]:
            with self.subTest(name=name):
                path = self.root / name
                before = path.read_bytes() if path.exists() else None
                if action == "remove":
                    path.unlink()
                else:
                    self.write(name, "changed fixture")
                result = self.cli("check")
                self.assertNotEqual(result.returncode, 0)
                self.assertIn(name, result.stderr)
                self.assertIn('"' + key + '"', result.stderr)
                if before is None:
                    path.unlink()
                else:
                    path.write_bytes(before)
        self.assertEqual(self.cli("check").returncode, 0)

    def test_manifest_recreation_cannot_rebind_running_suites(self):
        self.write("PhoneAgent/App.swift", "changed after suites began")
        self.cli("create", check=True)
        result = self.cli("check")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("captured digest", result.stderr)

    def test_corrupt_manifest_rejected(self):
        value = json.loads(self.manifest.read_text())
        value["files"]["Shared/Types.swift"] = "0" * 64
        self.manifest.write_text(json.dumps(value))
        self.assertNotEqual(self.cli("check").returncode, 0)

    def test_outputs_and_bytecode_are_not_inputs(self):
        self.write("output/run/log.txt", "synthetic output")
        self.write("Tests/__pycache__/fake.pyc", "generated bytecode")
        self.assertEqual(self.cli("check").returncode, 0)

    def runner(self, first_suite):
        # Run the actual production check.sh. Replace only its expensive child
        # programs with successful I/O fakes, then mutate a later input between
        # suites. This catches mixed-version green results beyond swiftc's own
        # single-invocation source-change check.
        import re
        script = (self.root / "scripts/check.sh").read_text()
        for name in re.findall(r'\$project_dir/(Tests/[^"\n]+\.(?:sh|py))', script):
            self.write(name, "exit 0\n" if name.endswith(".sh") else "pass\n")
        self.write("Tests/run.sh", first_suite)
        return subprocess.run(["bash", str(self.root / "scripts/check.sh")], cwd=self.root,
                              capture_output=True, text=True)

    def test_actual_runner_unchanged_success(self):
        result = self.runner("exit 0\n")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("Offline check input identity verified", result.stdout)

    def test_actual_runner_rejects_cross_suite_source_drift(self):
        result = self.runner("python3 - <<'PY'\nfrom pathlib import Path\nPath('PhoneAgent/App.swift').write_text('changed between successful suites')\nPY\n")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("PhoneAgent/App.swift", result.stderr)
        self.assertNotIn("Offline check input identity verified", result.stdout)

    def test_actual_runner_preserves_suite_failure_exit(self):
        result = self.runner("exit 7\n")
        self.assertEqual(result.returncode, 7)
        self.assertIn("Offline check input identity verified", result.stdout)

    def test_actual_runner_reports_drift_on_failed_suite_too(self):
        result = self.runner("python3 - <<'PY'\nfrom pathlib import Path\nPath('Tests/Fixture/input.json').write_text('changed fixture')\nPY\nexit 7\n")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("Tests/Fixture/input.json", result.stderr)


if __name__ == "__main__":
    unittest.main()
