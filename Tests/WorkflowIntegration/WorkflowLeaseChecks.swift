import Foundation
import CoreGraphics
import ImageIO
import UniformTypeIdentifiers

private enum WorkflowLeaseSyntheticError: Error { case recognition }

/// Standalone target; no changes to the existing integration main are needed.
/// Only the recognizer/capture/input boundaries are fake. Runtime, driver,
/// lease policy, ScreenFrame and the idle constructor are production code.
@MainActor enum WorkflowLeaseChecks {
    private static func jpeg(_ image: UIImage) -> Data {
        let bytes=NSMutableData(), destination=CGImageDestinationCreateWithData(bytes,UTType.jpeg.identifier as CFString,1,nil)!
        CGImageDestinationAddImage(destination,image.cgImage!,nil)
        precondition(CGImageDestinationFinalize(destination)); return bytes as Data
    }
    private static func frame(image:UIImage?=nil) -> ScreenFrame {
        let image=image ?? UIImage()
        return .init(image:image,jpeg:jpeg(image),capturedAt:Date(),sourceWidth:2,sourceHeight:2,fullDisplay:true,captureID:UUID())
    }
    private static func copy(_ frame:ScreenFrame,image:UIImage?=nil,jpeg:Data?=nil,pixel:Date?=nil,
                             confirmed:Date?=nil,capture:UUID?=nil,sourceWidth:Int?=nil,sourceHeight:Int?=nil,full:Bool?=nil) -> ScreenFrame {
        .init(image:image ?? frame.image,jpeg:jpeg ?? frame.jpeg,capturedAt:pixel ?? frame.capturedAt,
              sourceWidth:sourceWidth ?? frame.sourceWidth,sourceHeight:sourceHeight ?? frame.sourceHeight,
              fullDisplay:full ?? frame.fullDisplay,confirmedAt:confirmed ?? frame.confirmedAt,captureID:capture ?? frame.captureID)
    }
    private static func sizedImage(_ width:Int,_ height:Int) -> UIImage {
        let c=CGContext(data:nil,width:width,height:height,bitsPerComponent:8,bytesPerRow:width*4,
            space:CGColorSpaceCreateDeviceRGB(),bitmapInfo:CGImageAlphaInfo.premultipliedLast.rawValue)!
        return UIImage(cgImage:c.makeImage()!)
    }
    private static func element(_ id:String,_ label:String,_ x:Double,_ y:Double,_ width:Double,_ height:Double)->PhoneUIElement {
        .init(id:id,label:label,rect:.init(x:x,y:y,width:width,height:height),source:"ocr")
    }
    private static let marker=[element("synthetic-marker","Synthetic non-sensitive marker",0.3,0.4,0.4,0.05)]
    private static let roiCandidate=[element("account","Weixin ID: filehelper",0.214,0.170,0.347,0.016),
        element("about1","Transfer text, images, audio and video files",0.217,0.263,0.738,0.020),
        element("about2","between your device and your PC",0.217,0.283,0.581,0.020),
        element("messages","• Messages",0.378,0.347,0.247,0.021)]
    private static let title=element("synthetic-title","文件传输助手",0.2135,0.1338,0.29,0.0231)
    private static func state(_ capture:CaptureService,_ executor:MouseExecutor)->WorkflowObservationState {
        .init(frame:capture.frame,running:capture.running,selectedDeviceID:executor.ble.selectedID,
              accessoryReady:executor.ble.ready,connectionGeneration:executor.ble.pointerConnectionGeneration)
    }

    static func run(reportURL:URL?=nil) async throws -> Int {
        let directory=FileManager.default.temporaryDirectory.appendingPathComponent("WorkflowLease-"+UUID().uuidString)
        try FileManager.default.createDirectory(at:directory,withIntermediateDirectories:true)
        defer{try? FileManager.default.removeItem(at:directory)}
        var checks=0, failures:[String]=[], rows:[[String:Any]]=[]
        func expect(_ ok:Bool,_ label:String){checks+=1;if !ok{failures.append(label)}}
        func runtime(_ executor:MouseExecutor,recognize:@escaping (ScreenFrame)async throws->[PhoneUIElement],
                     title:((ScreenFrame)async throws->[PhoneUIElement])?=nil)->PhoneHarnessRuntime {
            PhoneHarnessRuntime(executor:executor,memoryURL:directory.appendingPathComponent(UUID().uuidString+".json"),
                recognize:recognize,recognizeWorkflowTitle:title)
        }
        func metrics()->RunMetricsRecorder {
            .init(taskID:UUID(),versions:.init(appVersion:"offline",appBuild:"fixture",sourceRevision:"workflow-lease-test",
                harnessVersion:"fixture",firmwareVersion:"none",model:"none",endpointHost:"none",device:"host-fake",
                operatingSystem:ProcessInfo.processInfo.operatingSystemVersionString,executionKind:.offlineReplay),directory:nil)
        }
        // Actual elapsed-time control: only explicit delivered synthetic idle
        // events publish a confirmation. No Date is generated by the getter.
        for mode in ["paired-full","paired-roi","paired-both","no-idle","ordinary-context","ordinary-workflow"] {
            let capture=CaptureService(), executor=MouseExecutor(), origin=frame()
            capture.frozenFrame=origin
            var fullCalls=0, roiCalls=0, idleDates:[Date]=[]
            func slow(_ deliverIdle:Bool) async throws {
                let event=Task{@MainActor in
                    try await Task.sleep(nanoseconds:1_400_000_000)
                    if deliverIdle {
                        let actual=Date();idleDates.append(actual)
                        capture.frozenFrame=workflowLeaseIdleFrame(previous:origin,now:actual,captureID:origin.captureID!,isFullDisplay:true)
                    }
                }
                do{try await Task.sleep(nanoseconds:1_650_000_000);try await event.value}
                catch{event.cancel();_ = try? await event.value;throw error}
            }
            let hasROI=mode == "paired-roi" || mode == "paired-both"
            let harness=runtime(executor,recognize:{_ in
                fullCalls+=1
                if mode != "paired-roi" {try await slow(mode != "no-idle")}
                return hasROI ? roiCandidate:marker
            },title:{_ in roiCalls+=1;try await slow(true);return [title]})
            let recorder=metrics();harness.metrics=recorder
            let gui=PhoneWorkflowCaptureDriver(capture:capture,executor:executor,harness:harness,initial:origin)
            let began=ProcessInfo.processInfo.systemUptime
            var accepted=false,returned:ScreenFrame?,snapshot:PhoneUISnapshot?,errorKind="none"
            do{
                if mode == "ordinary-context" {_ = try await harness.context(for:origin)}
                else if mode == "ordinary-workflow" {_ = try await harness.workflowSnapshot(origin)}
                else{let value=try await gui.read();returned=value.0;snapshot=value.1}
                accepted=true
            }catch{errorKind=String(reflecting:type(of:error))}
            let elapsed=(ProcessInfo.processInfo.systemUptime-began)*1000
            let shouldAccept=mode.hasPrefix("paired-")
            expect(accepted == shouldAccept,mode+" retains intended acceptance boundary")
            expect(elapsed>=1500 && Date().timeIntervalSince(origin.confirmedAt)>=1.5,mode+" really exceeds original confirmation lifetime")
            expect(fullCalls==1 && roiCalls==(hasROI ? 1:0),mode+" no recognition retry")
            expect(executor.actions.isEmpty && executor.pointerMoves.isEmpty,mode+" observes without input")
            if let returned,let snapshot{
                expect(returned.confirmedAt==idleDates.last && returned.image===origin.image && returned.image.cgImage===origin.image.cgImage && returned.jpeg==origin.jpeg,mode+" returns actual published original-pixel frame")
                expect(returned.capturedAt==origin.capturedAt && snapshot.capturedAt==origin.capturedAt,mode+" preserves original pixel/snapshot timestamp")
                expect((0..<1.5).contains(Date().timeIntervalSince(returned.confirmedAt)),mode+" uses current strict 1.5s age")
                expect(gui.lastFailure==nil,mode+" clears failure on successful read")
                // The next read must wait after the returned real confirmation,
                // rather than the expired original frame's confirmation.
                var waitedAfter:Date?
                capture.waitHandler={after,_ in
                    waitedAfter=after
                    try await Task.sleep(nanoseconds:1_000_000)
                    capture.frozenFrame=workflowLeaseIdleFrame(previous:origin,now:Date(),captureID:origin.captureID!,isFullDisplay:true)
                    return true
                }
                let next=try await gui.read()
                expect(waitedAfter==returned.confirmedAt && next.0.confirmedAt>returned.confirmedAt,mode+" next-read strict watermark uses actual returned confirmation")
                expect(fullCalls==1 && roiCalls==(hasROI ? 1:0),mode+" strong raw caches survive real idle without additional OCR")
            }else if mode == "no-idle"{
                expect(gui.lastFailure?.failedPredicates.contains(.confirmationAgeValid)==true,"timer alone cannot renew a lease")
            }
            let spans=recorder.snapshot.spans
            expect(spans.filter{$0.category == .ocr}.allSatisfy{$0.outcome == .completed},mode+" OCR completion metric remains recognition return, not adoption")
            if shouldAccept{expect(spans.contains{$0.label=="harness.workflow-lease-binding" && $0.outcome == .completed},mode+" lease verification has fixed metric label")}
            rows.append(["case":mode,"accepted":accepted,"elapsedMs":elapsed,"fullCalls":fullCalls,"roiCalls":roiCalls,
                "idleEvents":idleDates.count,"originalConfirmationAgeMs":Date().timeIntervalSince(origin.confirmedAt)*1000,
                "errorType":errorKind,"inputCount":executor.actions.count])
        }
        typealias Mutation=(CaptureService,MouseExecutor,ScreenFrame,PhoneHarnessRuntime)->Void
        let mutations:[(String,WorkflowCaptureFailure.Predicate,Mutation)]=[
            ("capture",.currentCaptureMatches,{c,_,f,_ in c.frozenFrame=copy(f,capture:UUID())}),
            ("pixel",.currentPixelsMatch,{c,_,f,_ in c.frozenFrame=copy(f,pixel:Date(),confirmed:Date())}),
            ("source-width",.currentSourceDimensionsMatch,{c,_,f,_ in c.frozenFrame=copy(f,sourceWidth:3)}),
            ("source-height",.currentSourceDimensionsMatch,{c,_,f,_ in c.frozenFrame=copy(f,sourceHeight:3)}),
            ("CG-width",.currentDimensionsMatch,{c,_,f,_ in c.frozenFrame=copy(f,image:sizedImage(3,2))}),
            ("CG-height",.currentDimensionsMatch,{c,_,f,_ in c.frozenFrame=copy(f,image:sizedImage(2,3))}),
            ("UIImage",.currentImageObjectMatches,{c,_,f,_ in c.frozenFrame=copy(f,image:UIImage(cgImage:f.image.cgImage!))}),
            ("CG-object",.currentCGImageObjectMatches,{c,_,f,_ in c.frozenFrame=copy(f,image:UIImage())}),
            ("JPEG",.currentJPEGMatches,{c,_,f,_ in var bytes=f.jpeg;bytes[0] ^= 1;c.frozenFrame=copy(f,jpeg:bytes)}),
            ("partial",.currentFullDisplay,{c,_,f,_ in c.frozenFrame=copy(f,full:false)}),
            ("selected",.expectedAccessoryMatches,{_,e,_,_ in e.ble.selectedID="other-synthetic-accessory"}),
            ("same-ID-new-connection",.connectionGenerationMatches,{_,e,_,_ in e.ble.pointerConnectionGeneration=UUID()}),
            ("not-ready",.accessoryReady,{_,e,_,_ in e.ble.ready=false}),
            ("reset",.runtimeGenerationMatches,{_,_,_,h in h.reset()}),
            ("stopped",.captureRunning,{c,_,_,_ in c.running=false}),
            ("current-missing",.currentFramePresent,{c,_,_,_ in c.frozenFrame=nil}),
            ("confirmation-before-pixel",.pixelBeforeConfirmation,{c,_,f,_ in c.frozenFrame=copy(f,confirmed:f.capturedAt.addingTimeInterval(-0.01))})
        ]
        for stage in ["full","roi"]{
            for(name,predicate,change)in mutations{
                let capture=CaptureService(), executor=MouseExecutor(), origin=frame();capture.frozenFrame=origin
                var fullCalls=0,roiCalls=0
                var harness:PhoneHarnessRuntime!
                harness=runtime(executor,recognize:{_ in
                    fullCalls+=1;await Task.yield()
                    if stage=="full"{change(capture,executor,origin,harness)}
                    return stage=="roi" ? roiCandidate:marker
                },title:{_ in roiCalls+=1;await Task.yield();change(capture,executor,origin,harness);return [title]})
                let gui=PhoneWorkflowCaptureDriver(capture:capture,executor:executor,harness:harness,initial:origin)
                var rejected=false
                do{_ = try await gui.read()}catch{rejected=true}
                expect(rejected && gui.lastFailure?.failedPredicates.contains(predicate)==true,stage+" rejects exact "+name+" predicate")
                expect(fullCalls==1 && roiCalls==(stage=="roi" ? 1:0),stage+" "+name+" no retry/adopted continuation")
                expect(executor.actions.isEmpty && executor.pointerMoves.isEmpty,stage+" "+name+" zero input")
                rows.append(["case":stage+"-"+name,"rejected":rejected,"expectedPredicate":predicate.rawValue,
                    "failedPredicates":gui.lastFailure?.failedPredicates.map(\.rawValue) ?? []])
            }
        }
        // Real-time floor: a previously published confirmation is replayed out
        // of order while both confirmations are younger than 1.5s.
        do{
            let capture=CaptureService(), executor=MouseExecutor(), origin=frame(), generation=UUID();capture.frozenFrame=origin
            let lease=try WorkflowObservationLease(frame:origin,after:.distantPast,runtimeGeneration:generation,
                selectedDeviceID:executor.ble.selectedID,connectionGeneration:executor.ble.pointerConnectionGeneration,current:{state(capture,executor)})
            _ = try lease.advance(runtimeGeneration:generation)
            try await Task.sleep(nanoseconds:1_000_000)
            let newer=workflowLeaseIdleFrame(previous:origin,now:Date(),captureID:origin.captureID!,isFullDisplay:true)
            capture.frozenFrame=newer;_ = try lease.advance(runtimeGeneration:generation)
            capture.frozenFrame=origin
            var found:[WorkflowLeaseFailure.Predicate]=[]
            do{_ = try lease.advance(runtimeGeneration:generation)}catch let e as WorkflowLeaseFailure{found=e.predicates}
            expect(found==[.confirmationNotRegressed],"floor rejects regression even though strict boundary and both real ages pass")
            expect((0..<1.5).contains(Date().timeIntervalSince(origin.confirmedAt)),"floor test is not accidentally a stale-frame rejection")
            let equal=try WorkflowObservationLease(frame:origin,after:origin.confirmedAt,runtimeGeneration:generation,
                selectedDeviceID:executor.ble.selectedID,connectionGeneration:executor.ble.pointerConnectionGeneration,current:{state(capture,executor)})
            found=[];do{_ = try equal.advance(runtimeGeneration:generation)}catch let e as WorkflowLeaseFailure{found=e.predicates}
            expect(found==[.confirmationAfterBoundary],"equal real boundary is never accepted")
        }
        // The same floor must hold through the actual full -> ROI pipeline,
        // not just the isolated policy. Both published dates are real/fresh.
        do {
            let capture=CaptureService(),executor=MouseExecutor(),origin=frame();capture.frozenFrame=origin
            var fullCalls=0,roiCalls=0
            let harness=runtime(executor,recognize:{_ in
                fullCalls+=1;try await Task.sleep(nanoseconds:1_000_000)
                capture.frozenFrame=workflowLeaseIdleFrame(previous:origin,now:Date(),captureID:origin.captureID!,isFullDisplay:true)
                return roiCandidate
            },title:{_ in
                roiCalls+=1;try await Task.sleep(nanoseconds:1_000_000)
                capture.frozenFrame=origin // out-of-order publication, never a new confirmation
                return [title]
            })
            let gui=PhoneWorkflowCaptureDriver(capture:capture,executor:executor,harness:harness,initial:origin)
            do {_ = try await gui.read()} catch {}
            expect(gui.lastFailure?.failedPredicates.contains(.confirmationNotRegressed)==true &&
                gui.lastFailure?.failedPredicates.contains(.confirmationAgeValid)==false,
                "actual full-to-ROI floor rejects regression without hiding behind age")
            expect(fullCalls==1 && roiCalls==1 && executor.actions.isEmpty,"full-to-ROI floor neither retries nor dispatches")
        }
        // A rejected or cancelled await must not adopt raw data into the strong
        // slot. The later independent read is an explicit test action, not a
        // production retry or permission to replay a submission.
        for stage in ["full","roi"] {
            for interruption in ["source-change","cancel"] {
                let capture=CaptureService(),executor=MouseExecutor(),origin=frame();capture.frozenFrame=origin
                var fullCalls=0,roiCalls=0,interrupt=true
                func boundary() {
                    if interrupt {
                        if interruption=="cancel" {withUnsafeCurrentTask{$0?.cancel()}}
                        else {capture.frozenFrame=copy(origin,image:UIImage(cgImage:origin.image.cgImage!))}
                    }
                }
                let harness=runtime(executor,recognize:{_ in
                    fullCalls+=1;await Task.yield();if stage=="full"{boundary()};return stage=="roi" ? roiCandidate:marker
                },title:{_ in roiCalls+=1;await Task.yield();boundary();return [title]})
                let first=Task {@MainActor in
                    do {_ = try await harness.workflowObservation(origin,after:.distantPast,current:{state(capture,executor)});return false}
                    catch is CancellationError {return interruption=="cancel"}
                    catch is WorkflowLeaseFailure {return interruption=="source-change"}
                    catch {return false}
                }
                expect(await first.value,stage+" "+interruption+" preserves the actual rejection/cancel type")
                interrupt=false;capture.frozenFrame=origin
                _ = try await harness.workflowObservation(origin,after:.distantPast,current:{state(capture,executor)})
                expect(fullCalls==(stage=="full" ? 2:1) && roiCalls==(stage=="roi" ? 2:0),
                    stage+" "+interruption+" rejected await was not stored in raw cache")
                expect(executor.actions.isEmpty,stage+" "+interruption+" independent observation is still zero input")
            }
        }
        // Metadata-only cache collisions: ordinary API's existing key policy
        // is unchanged; explicit workflows additionally require strong pixels.
        for changed in ["UIImage","CG","JPEG","connection"]{
            let capture=CaptureService(),executor=MouseExecutor(),original=frame();capture.frozenFrame=original
            var calls=0,roiCalls=0
            let harness=runtime(executor,recognize:{_ in calls+=1;return roiCandidate},title:{_ in roiCalls+=1;return [title]})
            _ = try await harness.workflowSnapshot(original) // populate existing raw slots
            var replacement=original
            if changed=="UIImage"{replacement=copy(original,image:UIImage(cgImage:original.image.cgImage!))}
            if changed=="CG"{replacement=copy(original,image:UIImage())}
            if changed=="JPEG"{var b=original.jpeg;b[0] ^= 1;replacement=copy(original,jpeg:b)}
            if changed=="connection"{executor.ble.pointerConnectionGeneration=UUID()}
            capture.frozenFrame=replacement
            _ = try await harness.workflowSnapshot(replacement)
            expect(calls==1 && roiCalls==1,changed+" ordinary weak-key semantics remain unchanged")
            let gui=PhoneWorkflowCaptureDriver(capture:capture,executor:executor,harness:harness,initial:replacement)
            _ = try await gui.read()
            expect(calls==2 && roiCalls==2,changed+" explicit workflow rejects weak-key cache reuse and re-recognizes")
            expect(executor.actions.isEmpty,changed+" cache test has no input")
        }
        // A current confirmation is always required on hits, and returned pairs
        // must be rechecked if reset occurs before the caller consumes them.
        do{
            let capture=CaptureService(),executor=MouseExecutor(),origin=frame();capture.frozenFrame=origin
            var calls=0
            let harness=runtime(executor,recognize:{_ in calls+=1;return marker})
            let pair=try await harness.workflowObservation(origin,after:.distantPast,current:{state(capture,executor)})
            harness.reset()
            var resetRejected=false
            do{_ = try harness.confirmWorkflowObservation(pair)}catch let e as WorkflowLeaseFailure{resetRejected=e.predicates.contains(.runtimeGenerationMatches)}
            expect(resetRejected,"reset after paired return cannot be hidden by caller continuation")
            let stale=copy(origin,confirmed:origin.capturedAt.addingTimeInterval(-2));capture.frozenFrame=stale
            var rejected=false
            do{_ = try await harness.workflowObservation(stale,after:.distantPast,current:{state(capture,executor)})}catch{rejected=true}
            expect(rejected && calls==1,"stale caller is rejected before cache/OCR even with earlier cache")
        }
        for stage in ["full","roi"]{
            let capture=CaptureService(),executor=MouseExecutor(),origin=frame();capture.frozenFrame=origin
            var fullCalls=0,roiCalls=0
            let harness=runtime(executor,recognize:{_ in
                fullCalls+=1;if stage=="full"{throw WorkflowLeaseSyntheticError.recognition};return roiCandidate
            },title:{_ in roiCalls+=1;throw WorkflowLeaseSyntheticError.recognition})
            var preserved=false
            do{_ = try await harness.workflowObservation(origin,after:.distantPast,current:{state(capture,executor)})}
            catch is WorkflowLeaseSyntheticError{preserved=true}
            expect(preserved && fullCalls==1 && roiCalls==(stage=="roi" ? 1:0),stage+" native recognition error is not replaced/retried")
            let cancelled=Task{@MainActor in
                let local=runtime(executor,recognize:{_ in
                    if stage=="full"{withUnsafeCurrentTask{$0?.cancel()}};return stage=="roi" ? roiCandidate:marker
                },title:{_ in withUnsafeCurrentTask{$0?.cancel()};return [title]})
                let gui=PhoneWorkflowCaptureDriver(capture:capture,executor:executor,harness:local,initial:origin)
                do{_ = try await gui.read();return false}
                catch is CancellationError{return gui.lastFailure?.stage == .cancelled && gui.lastFailure?.failedPredicates == [.taskNotCancelled]}
                catch{return false}
            }
            expect(await cancelled.value,stage+" cancellation keeps original type and fixed cancellation diagnostic")
            expect(executor.actions.isEmpty,stage+" error/cancel has no input")
        }
        // Final synchronous menu/domain callback cannot swap current pixels
        // after OCR validation and still return a stale paired observation.
        do{
            let capture=CaptureService(),executor=MouseExecutor(),origin=frame();capture.frozenFrame=origin
            let harness=runtime(executor,recognize:{_ in [element("cancel","Cancel",0.2,0.8,0.4,0.05)]})
            var menuCalled=false,rejected=false
            do{_ = try await harness.workflowObservation(origin,after:.distantPast,current:{state(capture,executor)},allowingMenu:{_ in
                menuCalled=true;capture.frozenFrame=copy(origin,image:UIImage());return true
            })}catch let e as WorkflowLeaseFailure{rejected=e.predicates.contains(.currentImageObjectMatches)}
            expect(menuCalled && rejected,"final menu policy boundary revalidates actual source before paired return")
        }
        // Strong proof remains bound before later input. We only exercise the
        // rejection branch: no test dispatches an actual fixture input.
        for changed in ["image","connection","reset","confirmation-regression"]{
            let capture=CaptureService(),executor=MouseExecutor(),origin=frame();capture.frozenFrame=origin
            let harness=runtime(executor,recognize:{_ in marker}),gui=PhoneWorkflowCaptureDriver(capture:capture,executor:executor,harness:harness,initial:origin)
            try await Task.sleep(nanoseconds:1_000_000)
            capture.frozenFrame=workflowLeaseIdleFrame(previous:origin,now:Date(),captureID:origin.captureID!,isFullDisplay:true)
            let value=try await gui.read()
            let expected:WorkflowCaptureFailure.Predicate
            switch changed {
            case "image":capture.frozenFrame=copy(value.0,image:UIImage(cgImage:origin.image.cgImage!));expected = .currentImageObjectMatches
            case "connection":executor.ble.pointerConnectionGeneration=UUID();expected = .connectionGenerationMatches
            case "reset":harness.reset();expected = .runtimeGenerationMatches
            default:capture.frozenFrame=origin;expected = .confirmationNotRegressed
            }
            var rejected=false;do{try await gui.tap(value.1.elements[0])}catch{rejected=true}
            expect(rejected && gui.lastFailure?.failedPredicates.contains(expected)==true && executor.actions.isEmpty,changed+" late change stops before input")
            if changed=="confirmation-regression" {
                expect(gui.lastFailure?.failedPredicates.contains(.confirmationAgeValid)==false &&
                    gui.lastFailure?.failedPredicates.contains(.pixelBeforeConfirmation)==false,
                    "input floor counterexample uses two valid fresh real confirmation dates")
            }
        }
        do{
            let capture=CaptureService(),executor=MouseExecutor(),origin=copy(frame(),jpeg:Data());capture.frozenFrame=origin
            var calls=0
            let harness=runtime(executor,recognize:{_ in calls+=1;return marker}),gui=PhoneWorkflowCaptureDriver(capture:capture,executor:executor,harness:harness,initial:origin)
            do{_ = try await gui.read()}catch{}
            expect(calls==0 && gui.lastFailure?.failedPredicates.contains(.sourcePixelsValid)==true,"empty fake JPEG never becomes strong source proof")
            let all=WorkflowCaptureFailure(stage:.observation,failedPredicates:WorkflowCaptureFailure.Predicate.allCases,
                timings:.init(confirmationAgeMs:.nan,pixelAgeMs:.infinity))
            expect(all.compactJSON.utf8.count<=400 && all.errorDescription!.count<500,"all fixed lease predicates retain diagnostic length budget")
            expect((try? JSONSerialization.jsonObject(with:Data(all.json.utf8))) != nil && (try? JSONSerialization.jsonObject(with:Data(all.compactJSON.utf8))) != nil,"NaN/Inf timings never mask failure JSON")
            expect(Set(WorkflowCaptureFailure.Predicate.allCases.map(\.compactCode)).count==WorkflowCaptureFailure.Predicate.allCases.count,"new diagnostic wire codes are unique and roundtrip")
            expect(WorkflowCaptureFailure.Predicate.allCases.allSatisfy{WorkflowCaptureFailure.Predicate(compactCode:$0.compactCode)==$0},"all diagnostic compact codes decode without enum-order assumptions")
        }
        try FileManager.default.removeItem(at:directory)
        let result:[String:Any]=["schemaVersion":1,"checks":checks,"failures":failures,"cases":rows,
            "realClockSlowRecognition":true,"explicitSyntheticIdleOnly":true,"gettersRetimed":false,
            "futureEpsilon":false,"realOSCallbacksOrDevicePerformanceClaimed":false,"noDeviceModelBLECalls":true,
            "temporaryFixturesCleaned":!FileManager.default.fileExists(atPath:directory.path)]
        if let reportURL{
            try FileManager.default.createDirectory(at:reportURL.deletingLastPathComponent(),withIntermediateDirectories:true)
            try JSONSerialization.data(withJSONObject:result,options:[.prettyPrinted,.sortedKeys]).write(to:reportURL,options:.atomic)
        }
        guard failures.isEmpty else{throw AgentError.message("WorkflowLease failures: "+failures.joined(separator:"; "))}
        return checks
    }
}
