const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const script = fs.readFileSync(path.join(__dirname, '../../PhoneAgent/Resources/XiaohongshuLocalReader.js'), 'utf8');
const id = '0123456789abcdef01234567', other = 'ffffffffffffffffffffffff';
let count = 0;
const check = (value, label) => { count++; assert.ok(value, label); };
function read(state, action, noteID = id, hostname = 'www.xiaohongshu.com') {
  const sandbox = { window: { __INITIAL_STATE__: state }, location: { protocol: 'https:', hostname } };
  Object.defineProperty(sandbox, 'document', { get() { throw Error('Reader must not access cookies/DOM globals'); } });
  sandbox.action = action; sandbox.noteID = noteID;
  return JSON.parse(vm.runInNewContext(script + '\nJSON.stringify(SelaXHSReader.snapshot(action, noteID))', sandbox));
}
const account = { userInfo: { value: { userId: id, nickname: '本机用户', guest: false } } };
check(read({ user: account }, 'status').account.id === id, 'Page user identity is required');
check(read({ user: { userInfo: { userId: id, guest: true } } }, 'status').account === null, 'Guest is not logged in');
check(read({ user: account }, 'status', id, 'xiaohongshu.com.evil.example').error === 'origin', 'Exact HTTPS site origin');
check(read({}, 'search').error === 'login', 'No user state cannot read');
check(read({ user: account, search: {} }, 'search').error === 'unsupported', 'Missing schema is not zero results');
const feed = { modelType: 'note', id, xsecToken: 'PRIVATE-REF', noteCard: { displayTitle: '标题', user: { nickName: '作者' } } };
let search = read({ user: account, search: { feeds: { _value: [feed, feed, { modelType: 'live_v2', id: other }] } } }, 'search');
check(search.payload.feeds.length === 1, 'Search deduplicates actual note cards');
check(search.payload.feeds[0].noteCard.user.nickname === '作者', 'Nickname variants');
check(!JSON.stringify(search).includes('userInfo'), 'Raw account/profile state is not returned');
search = read({ user: account, search: { feeds: [] } }, 'search');
check(search.payload.feeds.length === 0, 'Actual empty feed list is represented');
const detail = { note: { noteId: id, title: '标题', desc: 'a'.repeat(14000), user: { nickname: '作者' }, ignoredCookie: 'DO-NOT-RETURN' }, comments: { list: [{ id: 'c1', content: '评论', userInfo: { nickname: '读者', secret: 'DO-NOT-RETURN' }, subComments: [{ id: 'r1', content: '回复', userInfo: { nickname: '作者' } }] }] } };
let result = read({ user: account, note: { noteDetailMap: { [other]: { note: { noteId: other, title: '错误笔记' } }, [id]: detail } } }, 'detail');
check(result.payload.data.note.noteId === id && result.payload.data.note.title === '标题', 'Exact note selected, never first map entry');
check(result.payload.data.note.desc.length === 12001, 'One-character truncation sentinel retained for native cards');
check(result.payload.data.comments.list[0].subComments[0].content === '回复', 'Loaded comments/replies only');
check(!JSON.stringify(result).includes('DO-NOT-RETURN'), 'Unlisted page fields never leave WebView');
result = read({ user: account, note: { noteDetailMap: { [id]: { note: detail.note } } } }, 'detail');
check(!('comments' in result.payload.data), 'Unknown comment list remains unknown');
check(read({ user: account, note: { noteDetailMap: { [id]: detail } } }, 'detail', other).error === 'unsupported', 'Missing selected note fails closed');
